_INDEX: dict[str, Caliber] = {c.term: c for c in CALIBERS}
_ALIAS: dict[str, Caliber] = {}
for _c in CALIBERS:
    for _a in _c.aliases:
        _ALIAS.setdefault(_a, _c)


def lookup(term: str) -> Caliber | None:
    """按术语精确/别名/包含匹配取词条（抽不到返回 None，**不猜**）

    三档，从严到宽：**词条名精确** → **别名精确** → **互为子串**。
    别名这一档是必需的：护照里标注的是「性质:预计」，而词条名是「预测值」，
    没有别名就永远匹配不上——实测一次真实调研里 3 条带口径的引文一条都没命中，
    整块《口径对照》静默不出现（功能没坏，是两边用词不同）。
    """
    t = (term or "").strip()
    if not t:
        return None
    if t in _INDEX:
        return _INDEX[t]
    if t in _ALIAS:
        return _ALIAS[t]
    for k, v in _INDEX.items():
        if k in t or t in k:
            return v
    for k, v in _ALIAS.items():
        if k in t or t in k:
            return v
    return None


def explain(terms: list[str], limit: int = 6) -> str:
    """把报告里**实际用到**的口径 → 一段对照说明（没命中就一个字都不加）"""
    hits: list[Caliber] = []
    seen: set[str] = set()
    for t in terms or []:
        c = lookup(t)
        if c and c.term not in seen:
            seen.add(c.term)
            hits.append(c)
        if len(hits) >= limit:
            break
    if not hits:
        return ""
    lines = [
        "\n\n---\n\n# ⚖️ 口径对照（本报告用到的统计口径）",
        "本报告引用的数字涉及以下统计口径。它们**在报告里都被简写成'市场规模''门店数'这类词**，"
        "但含义差别很大——列在这里供核对，避免把不同口径的数当同一个东西比较：",
        "",
        "| 口径 | 它实际指什么 | 最容易被当成 | 混用的后果 |",
        "| :--- | :--- | :--- | :--- |",
    ]
    for c in hits:
        lines.append(f"| **{c.term}** | {c.defines} | {c.not_equal_to} | {c.trap} |")
    lines.append("")
    lines.append(
        "> 本节只解释**口径本身**，不判定某个具体数字用对没用对——那需要看到原始上下文，"
        "猜错比不说更糟。若正文两处引用了不同口径的同一个指标，请以各自标注的口径为准。"
    )
    return "\n".join(lines)
