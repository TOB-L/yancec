"""研策 · 引用遗漏层——"该引来源的那句话，到底引了没有"

## 这一层补的是前两层都看不见的盲区

- `core/verification.py`（**链接层**）：这条引用还活着吗 → 只审**已存在**的引用
- `core/entailment.py`（**内容层**）：这句话被这段原文支持吗 → 也只审**已存在**的引用
- **本模块（遗漏层）**：正文里那些**根本没有引用**的数字断言有多少 → 前两层对它们完全盲

它为什么重要：Google AI Overviews 的实测审计（arXiv 2605.14021，98,020 条
atomic claim）给出的结论是——**11.0% 的断言不被所引页面支持，而主导失败模式是
「遗漏（omission）」**：不是引错了，是**该引的地方压根没引**。

这解释了一个反直觉的现象：**一份"引文核验 100% 通过"的报告，可能有一半数字没来源。**
只报前两层，等于只审了被抓住的那部分。

## 为什么它必须和「支撑率」并排出现

我们的支撑率一度跑到 100%（9/9 全支撑）。**这个数比"低"更危险**——它会被读成
"你的核验器太松"（公开基线：DeepTRACE 40–80%、AIO 11.0% unsupported）。
把"遗漏层"并排报出来，叙事的性质就变了：

> "已存在的引用里 9/9 被原文支撑；**同时我们发现正文还有 N 处数字断言没有引用**。"

前者是自夸，后者是自审。**能自己找出自己没引的地方，才是这份报告可信的证据。**

## 判定纪律（三条）

1. **只扫正文**，不扫审计附录（附录里的表格是诊断产物，不是主张）。
   用 `core/report_html.split_audit_tail` 切分——与前端折叠用同一把刀，避免两处口径不一。
2. **只认"数字 + 单位"的断言**。"竞争激烈"这类定性句不算——它没有可核对的量。
3. **明确自陈是启发式**。它的价值在于"把没有来源的数字摆到台面上"，不在于精确计数；
   所以附录里逐条给出**样例原文**，让人工能一眼判断是真是假，而不是只给一个数。
"""
from __future__ import annotations

import re
from typing import Any

# 数字 + 单位：只认这些形态才算"可核对的量"。
# 刻意不把裸数字（如"第一/2026年"）算进来——年份不是断言，序数不是量。
_UNIT = (
    r"%|个百分点|亿元|万元|亿|万元|万家|亿美元|美元|元|万家|家|万人|人|万|"
    r"杯|座|次|倍|平方米|平米|吨|万辆|万台|亿元"
)
_NUM_UNIT = re.compile(rf"\d[\d,\.]*\s*(?:{_UNIT})")

# 已引用的标记。**这份清单是照着真实报告的实际写法定的，不是猜的**——
# 第一版只认 `<ref>` 与 `[N]`，跑真实报告得出"55 处断言只有 1 处带引用"，
# 而报告里明明写满了 `[技术环境/ IDC 2024年报告]` 与 `「国家统计局2025年数据」`。
# 那种误报会变成自伤：附录里印一个假的"98% 没引用"，比不印更糟。
#
# 判定用**结构特征**而不是机构名词表（名词表会随行业漂移、且漏一个就误报一片）：
#   · 方括号内含 4 位年份 或 域名  → [技术环境/ IDC 2024年报告] / [经济环境/ chinairn.com 2026年测算]
#   · 角括号内含 4 位年份 / 域名 / 「据」→ 「国家统计局2025年数据」 / 「chinairn.com 2026」
#   · 正文里的「据某某…数据/统计/报告/测算/预测/白皮书/年报」
_YEAR = r"(?:19|20)\d{2}"
_DOMAIN = r"[A-Za-z0-9\-]+\.(?:com|cn|org|gov|net|edu)"
_CITED = re.compile(
    r"<ref>"
    rf"|\[[^\]\n]{{0,60}}(?:{_YEAR}|{_DOMAIN})[^\]\n]{{0,40}}\]"
    rf"|「[^」\n]{{0,60}}(?:{_YEAR}|{_DOMAIN}|据)[^」\n]{{0,40}}」"
    r"|据[^，。；\n]{2,24}(?:数据|统计|报告|测算|预测|白皮书|年报|披露|口径)"
    # 主谓式归属：「IDC数据显示」「艾瑞报告指出」——主体在前、动词在后，与「据…」语序相反。
    # 实测踩中：`IDC数据显示，2026年县域市场咖啡渗透率预计达到34.2%` 被判成裸断言。
    r"|[^\s，。；、）(（]{2,20}(?:数据|报告|白皮书|年报|财报|统计|测算|预测)\s*(?:显示|表明|指出|披露|称|估算|预计)"
    # 行内归属：「瑞幸2024年报披露」「艾瑞2025白皮书」——主体+年份+文种，也是把来源摆出来了
    rf"|[^\s，。；、）(（]{{1,16}}{_YEAR}\s*年?\s*(?:年报|财报|半年报|季报|白皮书|报告|数据|统计|披露)"
    r"|（数据来源|\(数据来源"
    # 行内证据标记：`[证据: 社会环境/宏观环境]`——报告自己把来源摆出来了，
    # 只是没用方括号年份/域名的形式。病案：审计实测附录样例 #5
    # `*   依据：下沉市场客单价中位数仅 15.8 元…[证据: 社会环境/宏观环境]` 被判成裸断言。
    r"|\[证据[:：]"
    # **markdown 链接本身**：`[标题](https://…)`——URL 就是来源，且这是报告里最"可点"的形式。
    #
    # 病案（2026-09-15 深访实跑，真实报告）：时效补检块印的 4 行线索形如
    #   `- 🔗 [星巴克下沉千县开店超8000家,平价咖啡迎来新机遇 - 今日头条](https://www.toutiao.com/article/756…)（toutiao.com · 期未标注）`
    # 被算成**裸断言**并进了附录样例（8 条里占 2 条）。原因：`_DOMAIN` 只认
    # **方括号/角括号内**的域名，而这里域名在 `](…)` 的圆括号里、站点名在全角括号里
    # ——**一行明明白白带着可点 URL，却被印成"没有来源"**。
    # 这类误报的代价比漏报大：附录印的是"你的报告有 N 处没摆来源"，
    # 而其中一条自己就带着链接——读者会据此不再信这一层的其余读数。
    #
    # 与上一轮删掉 `"- ["` 前缀跳过**不是同一件事**：那条是"整行不算断言"（会漏掉
    # 最该计为已引用的那类行），这条是"算作已引用"——方向相反，且更准。
    r"|\]\(\s*<?https?://"
)

# **本报告自算**的数字：TAM/SAM/SOM、测算引擎输出、敏感性分析。
# 它们不是"引用"，本来就不该有外部来源——单列一档，避免把自研测算算成引用缺陷。
# **口径要窄**：只认"这段说的是本报告的测算结果"的标记。
# 实测踩中：第一版把「盈亏平衡」「单位经济模型」也收进来，于是
# 「单店日均杯量仅 48 杯，盈亏平衡周期延长至 14.3 个月」——一句**外部事实主张**——
# 被归进了"本报告自算"，直接从缺陷档里消失了。**漏报比误报更危险**。
_DERIVED = re.compile(
    r"TAM|SAM|SOM|测算引擎|本报告测算|据测算|外推|敏感性分析"
)

# 已**自我标注为不确定**的数字：`（L5估算）`、`（存疑·待核）`、`[政策环境/ L5估算]`、
# `（World Bank，单位：美元）`。它们没有可点的来源，但**明说了自己没有来源或说明了口径**——
# 这与"把无源数字当事实陈述"是两件事。把它们混进"遗漏"会把最诚实的那部分文字算成缺陷，
# 等于惩罚诚实。
_LABELED = re.compile(
    r"（[^）\n]{0,18}(?:L[1-5]|估算|待核|存疑|预测|情景|假设|口径待定)[^）\n]{0,18}）"
    r"|\([^)\n]{0,18}(?:L[1-5]|估算|待核|存疑|预测)[^)\n]{0,18}\)"
    r"|L[1-5]\s*(?:估算|推测|情景)"          # 裸写「L5估算」（常在方括号里）
    r"|\[\s*[^\]\n]{0,16}L[1-5][^\]\n]{0,16}\]"
    r"|（[^）\n]{0,24}单位[:：][^）\n]{0,16}）"  # 只标了口径没标来源，但**把口径说清了**
)

# 不算主张的行：标题 / 表格 / 引用块 / 计划与建议（这些数字是"打算怎么做"，不是"事实是什么"）
#
# 病案（2026-09-15 外部审计）：这里原先还有 `"- ["` 与 `"* ["`，用意是跳过"纯参考列表"行。
# 但它是**前缀匹配**，于是 `- [瑞幸2024年年报](https://…) 门店 22,340 家` 这类
# **带来源的正常断言行被整行跳过**——`claims` 少计、`cited` 也少计，
# 而且**恰好把最该被算作"已引用"的那一类漏掉**（漏报比误报更危险）。
# 已在绿档报告上实测：去掉这两项**影响 0 行**（那份报告没有这种行），
# 所以这是一处**潜在**漏报，不是现行错误——但仍然要修，因为它会在别的报告上发作。
# 表格行（`|`）与引用块（`>`）的过滤保持不变：它们确实不是"事实主张"。
_SKIP_PREFIX = ("#", "|", ">", "序号", "---")
# **计划类章节**：这些章节里的数字是"打算怎么做"，不是"事实是什么"——
# 与 `_SKIP_WORDS` 里那条"建议/行动/预算"是同一条纪律，但**按章节判而不是按词判**。
#
# 病案（2026-09-15 外部审计）：附录印出的 8 条样例里，**#3/#4/#6 全是误报**——
# 它们来自「## 行动清单（怎么做）」与「## 风险与对策」，形如
# `*   动作：筛选 GDP 增速高于全国平均…`、`*   对策：避免直接参与 9.9 元价格战…`。
# **那是计划，不是断言**。词表法漏掉了它们（"动作"不在 `_SKIP_WORDS` 里），
# 而"往词表里再加几个词"是治不完的——章节归属是**结构性**信息，比词表稳。
_SKIP_SECTION = re.compile(
    r"^#{2,4}\s*[^#\n]{0,30}?(行动清单|行动建议|风险与对策|对策建议|应对措施|"
    r"验证计划|执行计划|实施路径|下一步|里程碑|预算|时间表|怎么做|建议)"
)
_SKIP_WORDS = (
    "建议", "第一步", "第二步", "第三步", "行动", "预算", "负责人", "截止", "KPI",
    "停止条件", "Day ", "¥", "验证任务", "vt_", "执行顺序", "优先级", "时间表",
    "请核验", "待核", "正式决策前", "生成时点", "引擎基线",
    # 验证计划条目：那是"打算怎么验证"，不是"事实是什么"。
    # 实测踩中：「* 目的：确认用户…若无人愿意深度对话或明确需求比例<50%，立即终止项目」
    # 被算成了一条无源断言——那是一句**计划**，把它算进去纯属噪音。
    "目的：", "立即终止", "若无人愿意", "验证“", "终止项目",
)


def scan(md: str, max_samples: int = 8) -> dict[str, Any]:
    """扫正文，返回「有数字但没引用的断言」计数与样例。**纯规则、零模型成本。**"""
    if not md:
        return {}
    try:
        from core.report_html import split_audit_tail

        main_md, _audit = split_audit_tail(md)
    except Exception:
        main_md = md
    lines = (main_md or "").split("\n")

    total = cited = labeled = derived = 0
    samples: list[str] = []
    _skip_sec = False
    _skip_word_lines = 0
    for raw in lines:
        ln = (raw or "").strip()
        if not ln or len(ln) < 12:
            continue
        # **先判章节归属**（必须在 `_SKIP_PREFIX` 之前：`#` 开头的行会被前缀规则直接跳过，
        # 那样就永远读不到"当前在哪个章节"）。计划类章节里的数字是"打算怎么做"，不是断言。
        if ln.startswith("#"):
            _skip_sec = bool(_SKIP_SECTION.match(ln))
            continue
        if _skip_sec:
            continue
        if ln.startswith(_SKIP_PREFIX):
            continue
        # ⚠️ **词表否决只认"行首的计划标记"，不再对整行做子串匹配**（2026-09-16 全量审计）。
        #
        # 病案：原写法是 `if any(w in ln for w in _SKIP_WORDS): continue` ——
        # **整行子串否决**。于是一句真正的数字断言，只要句中**任何位置**出现
        # 「建议 / 预算 / 行动 / 截止 / 优先级 …」就被整行踢出分母。
        # 例如「2024 年现磨咖啡市场规模约 1,200 亿元，第三方建议按 8% 增速外推」——
        # 它是一条**有数字、有单位、无来源**的裸断言，正是这一层要找的东西，
        # 却因为夹了"建议"两个字被丢掉。
        # 后果不是"少算几条"，而是**裸断言读数系统性偏低**——**自审数字往好看的方向偏**，
        # 而这一层的全部价值就是"自己揭自己的短"。
        #
        # 判据改成**位置**：计划类词只有在**行首**（去掉项目符号之后的前 6 字内）出现，
        # 才说明这一行是"打算怎么做"；出现在句子中间的是行文，不是计划。
        # 章节归属那条规则（`_SKIP_SECTION`）继续兜结构性的部分——
        # 追加词表治不完的病，那条注释自己就写过。
        _lead = re.sub(r"^[\s>*\-•\d.、)）]+", "", ln)[:6]
        if any(w in _lead for w in _SKIP_WORDS):
            _skip_word_lines += 1
            continue
        if not _NUM_UNIT.search(ln):
            continue  # 没有"数字+单位" → 不是可核对的量，不算断言
        total += 1
        if _CITED.search(ln):
            cited += 1
            continue
        if _LABELED.search(ln):
            labeled += 1  # 无来源，但**明说了自己没有来源**（L5估算/待核/预测）
            continue
        if _DERIVED.search(ln):
            derived += 1  # **本报告自算**（TAM/SAM/SOM/测算），本来就不该有外部来源
            continue
        if len(samples) < max_samples:
            # 去掉 markdown 强调符，留可读原文
            samples.append(re.sub(r"\*\*|`", "", ln)[:110])

    # 「裸断言」= 有数字有单位、没有来源、没有自陈不确定、也不是本报告的自算结果。
    # 这才是 AIO 所说的 omission：**把一个没有来源的数字当成事实讲出来**。
    omitted = total - cited - labeled - derived
    return {
        "claims": total,           # 正文里带数字+单位的断言总数
        "cited": cited,            # 带来源标记的
        "labeled": labeled,        # 无来源但自陈"估算/待核/预测"的（诚实标注，不算缺陷）
        "derived": derived,        # 本报告自算（TAM/SAM/SOM/测算），不算引用缺陷
        "omitted": omitted,        # **裸断言：无来源、未自陈不确定、也非自算**
        "cite_rate": round(cited / total, 4) if total else None,
        "bare_rate": round(omitted / total, 4) if total else None,
        "samples": samples,
        # **被"计划类词"排除的行数**（2026-09-16）：分母是怎么来的要能被读者看见。
        # 这一层判的是"报告有没有把无来源的数字当事实讲"，
        # 排除规则的宽严直接决定分子——**排除本身就是一个口径，必须披露**。
        "excluded_plan_lines": _skip_word_lines,
        "method": (
            "启发式：数字+单位 ∧ 无来源标记 ∧ 无「估算/待核/预测」自陈 ∧ 非本报告自算。"
            "来源标记按结构识别（方/角括号内含年份或域名、据某某数据/报告/测算、"
            "某某数据显示/报告指出、主体+年份+文种）；只扫正文段落，不含表格与审计附录。"
            # ⚠️ **这里原本写的是「条数见 `excluded_plan_lines`」——那句话是一句空头支票**（2026-09-17 实跑发现）。
            #
            # 病案：`scan()` 确实返回了 `excluded_plan_lines`，但交付路径上
            # `graph.node_deliver` 对这个 dict 做的是**手写白名单投影**（逐个键抄），
            # 而白名单里没有它；`format_appendix_md` 也没印它。
            # 于是这句「条数见 X」**被原样印进每一份交付报告**，
            # 而 **X 在读者拿到的任何一件产物里都不存在**——报告让读者去看一个不存在的东西。
            #
            # 这与本仓库最顽固的那个缺陷同族（声明→生产者断链），但更难看：
            # 前面几次是材料里承诺、代码里没做；这一次是**产品自己印在交付物里承诺**。
            # 而且它专挑"排除规则会直接改变分子"这句最该被验证的话旁边失效——
            # 读者据 66.7% 引用覆盖率下判断时，恰恰拿不到那个会改变分母的行数。
            #
            # 修法：**不再指向字段名，直接把数印出来**。读者读到的报告里自带这个数，
            # 不需要去任何地方查；字段本身也补进了投影（`graph.py`），供机器消费。
            f"另有按章节（行动清单/风险对策/验证计划…）与**行首**计划标记另外排除了 "
            f"**{_skip_word_lines}** 行——排除规则会直接改变分子，故一并报出"
        ),
    }


def format_appendix_md(rep: dict[str, Any] | None) -> str:
    """遗漏层 → 报告附录片段（接在引用蕴涵核验之后）。无数据时不印空壳。"""
    if not rep or not rep.get("claims"):
        return ""
    lines = [
        "",
        # 标题里**不许写「行业普遍不报的一层」**（2026-09-15，K24）。
        # 那是"从沉默推否证"：别家没单列这一层，不能推出"别家不做这一层"
        # （闭源产品的报告里没有这一节，也不代表它内部没算）。
        # 而且这一行是**印在交付报告里**的——复核者直接读到，比材料里的同类句式更该守规矩。
        "### 🔍 遗漏层：正文里**没有来源**的数字断言",
        "",
        f"正文段落中带「数字 + 单位」的断言共 **{rep['claims']}** 处："
        f"带来源标记 **{rep['cited']}** 处 · "
        f"无来源但**自陈「估算/待核/预测」** {rep.get('labeled', 0)} 处 · "
        # ── 2026-09-18 第九跑：**这一档原来没印，读者加不回来** ──
        # 内部字段一直是四档（cited / labeled / derived / omitted），四者相加 == claims。
        # 但交付文本只印三档 → 读者自己加得 31 + 13 + 12 = 56 ≠ 62，
        # 看上去像"自陈计数不闭合"（外部审计就是这么读的，并据此判了第 4 次同型缺陷）。
        # **计数本身是闭合的：31 + 13 + 6 + 12 = 62。少的是这一行。**
        # 教训与遗漏层自己要讲的那件事同型：**不是算错了，是没摆出来。**
        f"**本报告自算（引擎产出，不依赖外部来源）** {rep.get('derived', 0)} 处 · "
        f"**既无来源、也未自陈不确定（裸断言）{rep['omitted']} 处**"
        + (f"。引用覆盖率 {rep['cite_rate'] * 100:.0f}%" if rep.get("cite_rate") is not None else "")
        + "。",
        "",
        f"> **四档相加即总数**：{rep['cited']} + {rep.get('labeled', 0)} + "
        f"{rep.get('derived', 0)} + {rep['omitted']} = {rep['claims']}。"
        "（这一行是给读者的加法口——少印一档，读者就会以为分子分母对不上。）",
        "",
        "> **为什么单列这一层**：链接层与内容层**只审已经存在的引用**——"
        "对「该引而没引」完全盲。而 Google AI Overviews 的实测审计（arXiv 2605.14021，"
        "98,020 条断言）显示，**主导失败模式恰恰是「遗漏」而非「引错」**。"
        "换句话说：**一份「引文核验 100% 通过」的报告，可能有相当一部分数字根本没有来源。**",
        "",
        "> **为什么把「自陈估算/待核」单算一档**：它们没有来源，但**它们明说了自己没有来源**。"
        "把这类算进「遗漏」会惩罚诚实——本产品一直在批评的正是「把无源数字当事实讲」，"
        "而不是「出现了无源数字」。所以只有**裸断言**才计入缺陷。",
        "",
        f"> 判定口径：{rep.get('method', '')}。**这是启发式，不是精确计数**——"
        "它的价值是把没有来源的数字摆到台面上，让人工能一眼判断，"
        "而不是让读者以为「没被列出来 = 都引了」。",
    ]
    if rep.get("samples"):
        lines += ["", "**裸断言样例（最多 8 条）**：", ""]
        for s in rep["samples"]:
            lines.append(f"- {s}")
        if rep["omitted"] > len(rep["samples"]):
            lines.append(f"- …另有 {rep['omitted'] - len(rep['samples'])} 处未列出")
    lines += [
        "",
        "> **这一层不证明什么**：裸断言**不等于**该数字是错的——"
        "它可能来自上文的引用、来自已核验的测算引擎、或属于常识量级。"
        "它证明的是：**这些位置没有把来源摆出来**，需要人工按需回查。",
    ]
    return "\n".join(lines)


def describe() -> str:
    return (
        "引用遗漏层：扫描报告正文，统计「带数字+单位的断言」中未附任何引用来源的比例，"
        "并逐条给出样例。补的是链接层与内容层共同的盲区——两层都只审已存在的引用，"
        "而行业实测（AIO 98,020 条断言）显示主导失败模式是「遗漏」而非「引错」。"
    )


def _cli(argv: list[str]) -> int:
    """命令行重放：`python -m core.omission <报告文件> [--appendix]`

    为什么必须有它（2026-09-15 外部审计）：材料里写着这一层的读数（"63 处断言…"），
    而**读者无法自己复算**——一个不可复现的数字，无论多准，都退化成了一句自述。
    有了这条命令，"这 59 处是怎么数出来的"变成一条可以当场跑给别人看的东西。
    与 `_lint_report.py`（规则层现场重放）同一条纪律：**可复现的结论才算结论。**

    输入可以是：`.md` 正文；或 `data/reports/*.json` 存档（自动取 `report` 字段）。
    """
    import json
    import os
    import sys

    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass
    if not argv:
        print(__doc__ or "")
        print("用法：python -m core.omission <报告.md 或 data/reports/xxx.json> [--appendix]")
        return 2
    path = argv[0]
    if not os.path.isfile(path):
        print(f"文件不存在：{path}")
        return 2
    text = open(path, encoding="utf-8", errors="replace").read()
    if path.lower().endswith(".json"):
        try:
            text = (json.loads(text) or {}).get("report") or ""
        except Exception as e:
            print(f"JSON 解析失败：{e}")
            return 2
    rep = scan(text)
    if "--appendix" in argv:
        print(format_appendix_md(rep))
        return 0
    print("=" * 70)
    print("研策 · 引用遗漏层现场重放")
    print("=" * 70)
    print(f"输入：{path}（{len(text):,} 字）")
    if not rep.get("claims"):
        print("  ⚠ 未检出任何「数字+单位」断言——**这不等于没有问题**，只说明本次没数出东西。")
        print("     请确认输入是**报告正文**（不是空文件/不是半截文本）。")
        return 0
    for k, label in (
        ("claims", "数字断言总数"),
        ("cited", "已附来源标记"),
        ("labeled", "自陈不确定"),
        ("derived", "本报告自算"),
        ("omitted", "**裸断言（无来源）**"),
    ):
        print(f"  {label:<18} {rep.get(k, 0)}")
    print(f"  {'引用率':<18} {(rep.get('cite_rate') or 0) * 100:.1f}%")
    print()
    print("口径：只扫**正文**（用 `report_html.split_audit_tail` 切分，与前端折叠同一把刀），")
    print("      不扫审计附录；只认「数字+单位」的断言。**判定为启发式**——")
    print("      它回答的是「这些位置有没有把来源摆出来」，不是「这些数字对不对」。")
    return 0


if __name__ == "__main__":
    import sys as _sys

    raise SystemExit(_cli(_sys.argv[1:]))
