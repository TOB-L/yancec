"""研策 · 数字护照（Number Passport）

## 为什么要有这一层

一份调研报告里，同一个数字换个口径就能差出 30%：
"2025 年咖啡市场规模"——是**零售额**还是**出货额**？**含加盟**还是**不含加盟**？
**规上企业**还是**全行业**？"数据期"是 2025 全年还是 2025H1？

行业里最常见的引用事故不是"引了假链接"，而是**数字真、口径不对**——
把"限额以上餐饮收入"当成"全行业收入"、把"2024 年数据"当成"最新数据"。
这类错误在报告正文里**看不出来**，因为数字本身是真的。

数字护照就是给每个数字配一张身份证：

    来源 · 层级 · 链接 · **数据期** · **口径**

复核者 30 秒可懂，且**口径未标注时如实写"未标注"**——不猜、不补、不美化。

## 诚实边界（重要）
- 只**抽取文本里显式出现**的口径/数据期标记（如"规上""含加盟""2025年报"）。
- 抽不到一律标 `未标注`——**绝不从上下文推断一个口径填进去**。
  填一个猜的口径比留空危险得多（会让人以为已核实过）。
- 本模块不改任何数字、不做单位换算，只做标注。
"""

from __future__ import annotations

import re
from dataclasses import dataclass

# ============================================================
# 数据期抽取
# ------------------------------------------------------------
# 按"信息量从强到弱"排序：能定到报告期/Q/月的，绝不退化成"某年"。
# 为什么强期优先：2025 年报 vs 2025Q1 的时效差 12 个月，而报告里都写成"2025"。
# ============================================================
_PERIOD_PATTERNS: tuple[tuple[str, str], ...] = (
    # 定期报告期（最强：明确到报告类型）
    (r"20(\d{2})\s*年?\s*(?:年度|全年)\s*报告", "{y}年报"),
    (r"20(\d{2})\s*年?\s*(?:半年度|上半年|中期)\s*报告", "{y}H1"),
    (r"20(\d{2})\s*年?\s*(?:三季度|第三季度)\s*报告", "{y}Q3"),
    (r"20(\d{2})\s*年?\s*(?:一季度|第一季度)\s*报告", "{y}Q1"),
    # 季度
    (r"20(\d{2})\s*年?\s*[Qq]([1-4])", "{y}Q{q}"),
    (r"20(\d{2})\s*年?\s*第\s*([一二三四1-4])\s*季度", "{y}Q{q}"),
    # 半年度
    (r"20(\d{2})\s*年?\s*(?:上半年|半年度|H1)", "{y}H1"),
    (r"20(\d{2})\s*年?\s*(?:下半年|H2)", "{y}H2"),
    # 年月（精确到月）
    (r"20(\d{2})\s*年\s*(\d{1,2})\s*月", "{y}-{m:02d}"),
    (r"20(\d{2})[-/](\d{1,2})(?![\d])", "{y}-{m:02d}"),
    # 仅年份（最弱，兜底）
    (r"20(\d{2})\s*年", "{y}"),
)
_CN_Q = {"一": "1", "二": "2", "三": "3", "四": "4"}


def extract_period(*texts: str) -> str:
    """从标题/正文/日期里抽取**数据期**（如 2025年报 / 2026H1 / 2026Q3 / 2026-08 / 2025）

    多段文本按顺序给（标题 → 摘录 → 发布日期），返回**第一个能定到的最强期**。
    抽不到返回 ""（上层写"未标注"）。
    """
    for pat, fmt in _PERIOD_PATTERNS:
        for t in texts:
            s = str(t or "")
            if not s:
                continue
            m = re.search(pat, s)
            if not m:
                continue
            g = m.groups()
            y = f"20{g[0]}" if g else ""
            if not y:
                continue
            q = ""
            if len(g) > 1 and g[1] is not None:
                raw = str(g[1])
                q = _CN_Q.get(raw, raw)
            try:
                return fmt.format(y=y, q=q, m=int(g[1]) if len(g) > 1 and str(g[1]).isdigit() else 0)
            except Exception:
                continue
    return ""


# ============================================================
# 口径抽取
# ------------------------------------------------------------
# 只认"显式写出来的统计口径词"。这些词在统计公报/研报里是**术语**，
# 出现即代表作者声明了口径，抽取是安全的；没出现就绝不推断。
# ============================================================
# 每组 = (维度名, **否定式**, **肯定式**)。
# ⚠️ 结构必须**显式分正负**，不能只用一个词表靠"谁先匹配"：
#   病案（2026-09-14 审计）：原表把 `"含加盟"` 与 `"不含加盟"` 混在一组里顺序匹配，
#   而 `"不含加盟"` **包含子串** `"含加盟"` → 正文写着"不含加盟店"的引用（瑞幸/蜜雪财报常见措辞）
#   被印成「口径：含加盟」——**方向判反，把不含加盟的数说成含加盟的**（量级能差数倍），
#   而且这是我们**主动写错**，比留空"未标注"危险得多（本模块红线就是"不猜"）。
#   核验还指出：改成"按长度降序"**修不好**——`"含加盟店"`(4字) 与 `"不含加盟"`(4字) 等长，
#   稳定排序保持原序，`含加盟店` 仍会先命中。所以必须**先判否定式，命中即跳过本维度**。
_CALIBER_GROUPS: tuple[tuple[str, tuple[str, ...], tuple[str, ...]], ...] = (
    ("加盟口径",
     ("不含加盟", "不含加盟店", "直营口径", "直营店口径", "全部直营", "仅直营"),
     ("含加盟", "含加盟店")),
    ("税口径",
     ("不含税", "税后"),
     ("含税", "税前")),
    ("门店口径",
     ("仅连锁门店", "不含夫妻店", "不含无品牌小店"),
     ("全部门店", "全口径门店")),
    ("统计范围",
     (),
     ("规模以上", "规上", "限额以上", "限上", "全口径", "全行业", "全样本")),
    ("计价口径",
     (),
     ("零售额", "零售口径", "销售额", "出货量", "出货口径", "出厂价", "终端价", "终端零售", "GMV", "成交额")),
    ("人口口径",
     (),
     ("常住人口", "户籍人口", "城镇人口", "适龄人口")),
    ("业态口径",
     (),
     ("线上线下一体", "外卖口径", "堂食", "线上", "线下")),
)


def extract_period_from_url(url: str) -> str:
    """从 URL 的日期路径抽数据期——**抽取，不是推断**（URL 里的年月就是该页出版期）

    实测报告(10)：17 条引用里 **7 条"未能定位数据期"**，而其中相当一部分的 URL 本身就带年月
    （`/202609/t20260901_…` 这类政府站文章路径），只是我们没去读它。
    读 URL 里的日期与"从上下文猜一个口径"是两回事：前者是原文事实，后者是编。
    """
    u = str(url or "")
    if not u:
        return ""
    for pat in (r"/20(\d{2})(0[1-9]|1[0-2])(?:/|$|[^0-9])", r"/20(\d{2})-(0[1-9]|1[0-2])/", r"/20(\d{2})/(0[1-9]|1[0-2])/"):
        m = re.search(pat, u)
        if m:
            return f"20{m.group(1)}-{int(m.group(2)):02d}"
    return ""


# 口径**要素**：正式统计术语（_CALIBER_GROUPS）一个都没有时，退而求其次抽取
# **文本里明确写着**的限定词，并**自带标签**。
# 为什么带标签：这是"范围/性质/主体"三个不同的维度，混成一个字符串会被读成"这就是口径定义"。
# `范围:三线及以下；性质:预测值` 说的是"原文这么限定的"，不是"我们判定它就是这个口径"。
_CALIBER_ELEMENTS: tuple[tuple[str, tuple[str, ...]], ...] = (
    ("范围", ("全国城镇", "全国", "城镇", "乡村", "农村", "一线城市", "新一线", "二线城市",
              "三线城市", "三四线", "三线及以下", "县域", "下沉市场", "华东", "华南", "华北")),
    ("性质", ("预测值", "预计", "预估", "估算", "实际值", "目标值", "规划值", "初步核算")),
    ("主体", ("连锁", "加盟", "直营", "联营", "单店", "全渠道", "线上", "线下")),
)


def extract_caliber(*texts: str) -> str:
    """从标题/摘录里抽取**口径**标记；抽不到返回 ""（上层写"未标注"）

    可能命中多组（如"限额以上零售额"）→ 用 `+` 连接，**不合并、不改写**。
    正式统计术语一个都没有时，退一步抽**口径要素**（范围/性质/主体，各带标签）——
    实测报告(10) 的护照里 10 条有 9 条"口径未标注"，那列等于白留；
    而这些来源里多数其实写了"三四线""预测值"这类限定，只是我们没抽。
    """
    found: list[str] = []
    for _group, negs, poss in _CALIBER_GROUPS:
        # **先判否定式**：命中否定式就记它，并**跳过本维度的全部肯定式**
        # （"不含加盟店"里含子串"含加盟"，先判肯定式就会把方向判反）
        hit = ""
        for t in texts:
            sv = str(t or "")
            if not sv:
                continue
            hit = next((k for k in negs if k in sv), "")
            if hit:
                break
        if not hit:
            for t in texts:
                sv = str(t or "")
                if not sv:
                    continue
                hit = next((k for k in poss if k in sv), "")
                if hit:
                    break
        if hit and hit not in found:
            found.append(hit)
    if found:
        return "+".join(found[:3])
    elems: list[str] = []
    for label, kws in _CALIBER_ELEMENTS:
        for t in texts:
            s = str(t or "")
            if not s:
                continue
            hit = next((k for k in kws if k in s), None)
            if hit:
                elems.append(f"{label}:{hit}")
                break
    return "；".join(elems[:3])


@dataclass
class Passport:
    """一个数字/引用的身份证"""

    period: str = ""      # 数据期
    caliber: str = ""     # 口径
    period_src: str = ""  # 数据期从哪来的（title/excerpt/date）——用于自证不是编的

    def period_text(self) -> str:
        return self.period or "未标注"

    def caliber_text(self) -> str:
        return self.caliber or "未标注"

    def line(self) -> str:
        """一行式护照（报告脚注/证据卡用）"""
        return f"数据期：{self.period_text()}｜口径：{self.caliber_text()}"


def build_passport(title: str = "", excerpt: str = "", date: str = "", url: str = "") -> Passport:
    """给一条引用/证据造护照（诚实优先：抽不到就空，不猜）

    数据期**只从标题与摘录两处抽**：标题 → 摘录。抽不到就标「未标注」。
    （2026-09-18 审计：本 docstring 此前写的是**四步**，含"发布日期 → URL 里的日期路径"，
    而实现里只剩两步——那两步是 2026-09-14 审计**有意**删掉的，理由写在下面函数体的
    内联注释里，**但这句话没跟着改回来**。契约与实现不同源，是本次审计在四个模块里
    撞到的同一个病。）

    保留 `date` / `url` 两个入参：调用方仍在按引用四元组传入
    （见 `agents/researchers.py`），删签名会波及调用点，故登记在
    `_fulltest.py::_PW_DEAD_PARAM_OK` 并具名说明，而不是让它红着。
    """
    cal = extract_caliber(title, excerpt)
    # 数据期**只从标题与摘录里抽**——它们是"这份材料在讲哪个时期的数据"。
    #
    # ⚠️ 刻意**不再**用「发布日期」与「URL 年月路径」（2026-09-14 审计）：
    # 那两者是**页面出版期**，不是**数据期**。一篇 2026-09 发布、讲 2023 年数据的回顾稿，
    # 会被标成「数据期 2026-09」——护照在打自己的脸，而且后续的时效门拿着这个假数据期
    # 去判"这条来源够不够新"，等于用一个我们自己编的日期做判断。
    # 实测产物 `sources.csv` 里 World Bank 那条的 `data_period=2026-07`（其实那是**库更新日**，
    # 数据止于 2024）。**覆盖率下降是诚实的代价**：宁可标"未标注"，也不印一个错的数据期。
    for src, txt in (("title", title), ("excerpt", excerpt)):
        p = extract_period(txt)
        if p:
            return Passport(period=p, caliber=cal, period_src=src)
    return Passport(period="", caliber=cal, period_src="")


