    return (
        "指标时效基准：时效门不再是一刀切的年限，而是**按指标更新频率分档**——"
        "快变（门店/价格/榜单）1 年、常变（份额/融资/营收）2 年、稳变（人口/GDP/社零）3 年、"
        "慢变（行业规模/CAGR）4 年、普查与制度类 6 年。"
        "同一个「3 年」，对人口公报太严、对门店数太松；时效不是年份问题，是指标的更新频率问题。"
    )
