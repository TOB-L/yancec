"""指标时效基准：不同指标的"保鲜期"不一样，一刀切 3 年两头都错

## 为什么需要它

原来的时效门是一条**全局年限**：权威域免检、研究机构 5 年、其余 3 年。
问题不在宽严，在**它与指标无关**：

- 一份 **2021 年**的统计局人口公报，在 2026 年是**正常且必要**的引证
  （常住人口年度序列本来就该回溯几年做趋势），3 年门会把它误杀；
- 一条 **2023 年**的"某品牌门店数"，在 2026 年**已经没有任何参考价值**
  （连锁餐饮一年开关店能到两成），3 年门却放它过。

**同一个"3 年"，对前者太严、对后者太松。** 时效不是年份问题，是**指标的更新频率**问题。

## 怎么定档

按指标的**官方发布频率**与**商业变动速度**取两者中更紧的那个：

| 档 | 年限 | 判据 | 典型指标 |
|---|---|---|---|
| 快变 | 1 年 | 门店/价格/榜单类，一年内可显著变化 | 门店数、开关店、均价、单杯价、排名 |
| 常变 | 2 年 | 有季度/年度发布，且份额会挪动 | 市占率、渗透率、用户数、融资、营收 |
| 稳变 | 3 年 | 年度发布，结构变化慢 | 人口、GDP、社零、居民收入 |
| 慢变 | 4 年 | 咨询机构测算，口径与方法稳定 | 行业规模、CAGR、TAM |
| 缓变 | 6 年 | 普查类（5 年一次）与制度类 | 经济普查、人口普查、标准/法规 |

## 边界（勿越）

- **只调年限，不改判定逻辑**：仍然只认 4 位年份，抽不到年份一律放行。
- **权威域依旧整体豁免**（相关性来自角色而非题材），本档只在"非权威域"这一侧生效。
- `sniff()` 抽不出指标词时返回 `None`，调用方**退回原来的全局年限**——
  宁可维持现状，也不拿一个瞎猜的年限去卡来源。
"""
from __future__ import annotations

import re
from dataclasses import dataclass


@dataclass(frozen=True)
class FreshnessRule:
    key: str            # 档位机器码
    label: str          # 中文名
    years: int          # 可接受陈旧度（年）
    why: str            # 为什么是这个年限（会进报告，须是"能对外讲"的理由）
    markers: tuple[str, ...]  # 指标词（高精度，宁可少认）


RULES: tuple[FreshnessRule, ...] = (
    FreshnessRule(
        "fast", "快变指标", 1,
        "门店/价格/榜单类一年内即可显著变化（连锁餐饮年开关店率可达两成），跨年引用会失真",
        ("门店数", "门店数量", "店铺数", "开关店", "闭店", "新开门店", "在营门店",
         "客单价", "单价", "均价", "单杯", "人均消费", "翻台率", "日销", "店均",
         "排名", "排行榜", "榜单", "TOP10", "前十"),
    ),
    FreshnessRule(
        "moving", "常变指标", 2,
        "有季度或年度发布，且份额/融资格局挪动快，两年内基本完成一轮洗牌",
        ("市占率", "市场份额", "集中度", "CR5", "CR10", "渗透率", "覆盖率",
         "用户数", "月活", "MAU", "DAU", "会员数", "复购", "融资", "估值", "IPO",
         "营收", "净利润", "毛利", "同店", "单店", "GMV", "订单量", "销量",
         "外卖", "线上占比", "加盟商", "供应商"),
    ),
    FreshnessRule(
        "stable", "稳变指标", 3,
        "年度发布，总量与结构变化慢，三年内仍在有效区间",
        ("常住人口", "户籍人口", "人口", "城镇化", "GDP", "国内生产总值",
         "社会消费品零售", "社零", "居民收入", "可支配收入", "人均GDP",
         "就业", "失业率", "CPI", "PPI", "工业增加值", "固定资产投资", "进出口"),
    ),
    FreshnessRule(
        "slow", "慢变指标", 4,
        "机构测算口径与方法稳定，一份行业规模测算四五年内仍是常用引用口径",
        ("市场规模", "行业规模", "CAGR", "复合增长", "增长率", "增速", "TAM", "SAM", "SOM",
         "天花板", "容量", "行业报告", "白皮书", "调研报告", "产业规模"),
    ),
    FreshnessRule(
        "census", "普查/制度类", 6,
        "普查五年一次、制度与标准类以修订为周期，六年的陈旧度属正常引用范围",
        ("普查", "经济普查", "人口普查", "农业普查", "统计年鉴", "国家标准",
         "行业标准", "条例", "管理办法", "分类目录", "统计制度"),
    ),
)

_INDEX: tuple[tuple[re.Pattern[str], FreshnessRule], ...] = tuple(
    (re.compile("|".join(re.escape(m) for m in r.markers), re.I), r) for r in RULES
)


def sniff(indicator: str) -> FreshnessRule | None:
    """从指标/结论文本里嗅出时效档位（嗅不出返回 None → 调用方退回全局年限）

    按 `RULES` 顺序**先命中先返回**：档位表是**从紧到松**排的，
    所以"门店数同比"这种同时含快变与稳变词的，取更紧的"快变"——
    时效门上**宁可从严**（少一条旧来源，好过引一条废数字）。
    """
    t = str(indicator or "")
    if not t:
        return None
    for pat, rule in _INDEX:
        if pat.search(t):
            return rule
    return None


def max_age_for(indicator: str, default: int = 3) -> tuple[int, str]:
    """→ (可接受陈旧度年数, 理由)。嗅不出档位时返回 (default, "")"""
    r = sniff(indicator)
    if r is None:
        return default, ""
    return r.years, r.why


